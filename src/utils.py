def format_percentage(val):
    if pd.isna(val):
        return "N/A"
    return f"{float(val):.1f}%"

def format_gpa(val):
    if pd.isna(val):
        return "N/A"
    return f"{float(val):.2f}"

def generate_student_report_card(student_row, student_subjects_df):
    """
    Generates a clean text/markdown academic transcript for a single student.
    """
    report = []
    report.append("=" * 60)
    report.append(f"🎓 OFFICIAL ACADEMIC TRANSCRIPT & PERFORMANCE REPORT")
    report.append("=" * 60)
    report.append(f"Student ID       : {student_row['student_id']}")
    report.append(f"Student Name     : {student_row['name']}")
    report.append(f"Department       : {student_row['department']}")
    report.append(f"Year & Section   : Year {student_row['year']} - Section {student_row['section']}")
    report.append(f"Gender           : {student_row['gender']}")
    report.append("-" * 60)
    report.append(f"Cumulative GPA   : {student_row['gpa']} / 10.0")
    report.append(f"Average Marks    : {student_row['average_marks']}%")
    report.append(f"Attendance Rate  : {student_row['overall_attendance_pct']}% ({student_row['attendance_category']})")
    report.append(f"Standing Tier    : {student_row['performance_category']}")
    report.append(f"Overall Result   : {student_row['pass_status']}")
    report.append(f"Risk Assessment  : {student_row['risk_level']}")
    report.append(f"Department Rank  : #{student_row['dept_rank']}")
    report.append(f"Class Rank       : #{student_row['overall_rank']}")
    report.append("=" * 60)
    report.append("COURSE-WISE BREAKDOWN:")
    report.append(f"{'Subject':<18} | {'Int(20)':<7} | {'Mid1(25)':<8} | {'Mid2(25)':<8} | {'Ass(10)':<7} | {'Fin(100)':<8} | {'Score%':<7} | {'Att%':<6} | {'Status'}")
    report.append("-" * 88)
    
    for _, row in student_subjects_df.iterrows():
        report.append(
            f"{row['subject']:<18} | "
            f"{row['internal']:<7.1f} | "
            f"{row['mid1']:<8.1f} | "
            f"{row['mid2']:<8.1f} | "
            f"{row['assignment']:<7.1f} | "
            f"{row['final']:<8.1f} | "
            f"{row['normalized_score']:<7.1f} | "
            f"{row['attendance_pct']:<6.1f} | "
            f"{row['subject_status']}"
        )
    report.append("=" * 88)
    report.append("Generated by Student Performance Analytics Platform")
    report.append("=" * 88)
    return "\n".join(report)

def convert_df_to_csv(df):
    """Encodes a DataFrame into UTF-8 CSV bytes for Streamlit download button."""
    return df.to_csv(index=False).encode("utf-8")
